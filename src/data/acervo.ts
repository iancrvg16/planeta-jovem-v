export const midias = generated as Media[]
const normalize = (s: string) =>
  s
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '')
export function mediaFile(name: string): Media {
  const media = midias.find((m) => normalize(m.original) === normalize(name))
  if (!media) throw new Error(`Mídia não encontrada: ${name}`)
  return media
}

function entry(
  id: string,
  paisSlug: CountrySlug,
  titulo: string,
  descricao: string,
  arquivos: string[] = [],
  responsaveis: string[] = [],
  dataISO?: string,
  hora?: string,
  tags: string[] = [],
  stage: { fase?: string; atividade?: number } = {},
): Delivery {
  return {
    id,
    paisSlug,
    titulo,
    descricao,
    midias: arquivos.map(mediaFile),
    responsaveis,
    dataISO,
    hora,
    tags,
    fase: stage.fase ?? 'fase-1',
    atividade: stage.atividade ?? 1,
  }
}
