export function impactNumbers(now = new Date()) {
  const day = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'America/Fortaleza',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(now)
  const elapsed = Math.max(
    0,
    Math.floor(
      (Date.parse(`${day}T12:00:00Z`) -
        Date.parse(`${siteConfig.marcoZero}T12:00:00Z`)) /
        86400000,
    ),
  )
  return [
    { value: paises.length, label: 'Países virtuais' },
    { value: authors.length, label: 'Pessoas creditadas' },
    { value: entregas.length, label: 'Entregas publicadas' },
    { value: documentos.length + 1, label: 'Documentos oficiais' },
    { value: elapsed, label: 'Dias de jornada' },
  ]
}
export function mediaTitle(m: Media) {
  return (
    entregas.find((e) => e.midias.some((i) => i.id === m.id))?.titulo ??
    m.original
  )
}
export function dateLabel(e: Delivery) {
  return e.dataISO
    ? new Intl.DateTimeFormat('pt-BR', {
        day: '2-digit',
        month: 'short',
        year: 'numeric',
        timeZone: 'UTC',
      }).format(new Date(`${e.dataISO}T12:00:00Z`)) +
        (e.hora ? ` · ${e.hora}` : '')
    : `Fase ${e.fase.replace('fase-', '')} · data não informada`
}
